import { readdir, readFile, writeFile } from "node:fs/promises";
import * as path from "node:path";
import type { Metafile } from "esbuild";

// Packages that ship in dist/ but never appear as metafile inputs: the Tailwind
// plugin generates main.css itself, so esbuild only sees src/frontend/styles.css.
const EXTRA_PACKAGES = ["tailwindcss"];

const HEADER = `File Navigator includes third-party software that is bundled into its
distributed files. This file lists each bundled package with its license
and any notices it requires.

This file is generated by the production build (npm run build). Do not edit it.
`;

const RULE = "=".repeat(80);
const THIN_RULE = "-".repeat(80);

interface PackageJson {
	name: string;
	version: string;
	license?: string;
	repository?: string | { url?: string };
}

/** The package directories (node_modules/<name> or node_modules/@scope/<name>) bundled into any output. */
function bundledPackageDirs(metafile: Metafile): Set<string> {
	const dirs = new Set<string>();
	for (const [outputPath, output] of Object.entries(metafile.outputs)) {
		if (outputPath.endsWith(".map")) {
			continue;
		}
		for (const [input, { bytesInOutput }] of Object.entries(output.inputs)) {
			// Tree-shaken modules are listed with 0 bytes; they don't ship.
			const match = bytesInOutput > 0 && input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
			if (match) {
				dirs.add(match[1]);
			}
		}
	}
	return dirs;
}

function repositoryUrl(pkg: PackageJson): string {
	const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
	if (!repo) {
		return `https://www.npmjs.com/package/${pkg.name}`;
	}
	if (/^[\w.-]+\/[\w.-]+$/.test(repo)) {
		return `https://github.com/${repo}`;
	}
	return repo
		.replace(/^github:/, "https://github.com/")
		.replace(/^git\+/, "")
		.replace(/^git:\/\//, "https://")
		.replace(/^git@github\.com:/, "https://github.com/")
		.replace(/\.git$/, "");
}

async function findFile(dir: string, pattern: RegExp): Promise<string | undefined> {
	const name = (await readdir(dir)).find((file) => pattern.test(file));
	return name && path.join(dir, name);
}

async function packageSection(dir: string): Promise<{ name: string; text: string }> {
	const pkg: PackageJson = JSON.parse(await readFile(path.join(dir, "package.json"), "utf8"));
	const licenseFile = await findFile(dir, /^licen[cs]e(\.(md|txt))?$/i);
	if (!licenseFile) {
		throw new Error(`${pkg.name}: no LICENSE file found in ${dir}; add its notice by hand`);
	}
	const noticeFile = await findFile(dir, /^notice(\.(md|txt))?$/i);

	let text = [
		RULE,
		`${pkg.name} ${pkg.version}`,
		`License: ${pkg.license ?? "see below"}`,
		repositoryUrl(pkg),
		RULE,
		"",
		(await readFile(licenseFile, "utf8")).trimEnd(),
		"",
	].join("\n");
	if (noticeFile) {
		text += ["", THIN_RULE, "NOTICE", THIN_RULE, "", (await readFile(noticeFile, "utf8")).trimEnd(), ""].join("\n");
	}
	return { name: pkg.name, text };
}

/** Write ThirdPartyNotices.txt with the license (and NOTICE) of every package bundled into the outputs. */
export async function writeThirdPartyNotices(metafile: Metafile, outFile: string): Promise<void> {
	const dirs = bundledPackageDirs(metafile);
	for (const name of EXTRA_PACKAGES) {
		dirs.add(path.join("node_modules", name));
	}
	const sections = await Promise.all([...dirs].map(packageSection));
	sections.sort((a, b) => a.name.localeCompare(b.name));
	await writeFile(outFile, [HEADER, ...sections.map((section) => section.text)].join("\n"));
	console.log(`Wrote ${outFile} (${sections.map((section) => section.name).join(", ")})`);
}
